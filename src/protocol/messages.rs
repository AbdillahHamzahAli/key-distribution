//! Typed protocol messages carried as newline-delimited JSON.

use std::fmt;

use serde::{Deserialize, Deserializer, Serialize, Serializer};
use thiserror::Error;

use crate::crypto::codec::{CodecError, Hex};
use crate::crypto::modes::ModeError;

#[derive(Debug, Error)]
pub enum MessageError {
    #[error("{field} must not be empty")]
    Empty { field: &'static str },
    #[error("{field} must be ASCII only: {value:?}")]
    NotAscii { field: &'static str, value: String },
    #[error("{field} must not contain control characters: {value:?}")]
    ControlChar { field: &'static str, value: String },
    #[error("{field} must not contain '|': {value:?}")]
    Delimiter { field: &'static str, value: String },
    #[error("nonce must be decimal digits, got {value:?}")]
    NonceFormat { value: String },
    #[error("session key must be 16 characters, got {0}")]
    SessionKeyLength(usize),
    #[error("nonce mismatch: expected {expected:?}, sent {actual:?}")]
    NonceMismatch { expected: String, actual: String },
    #[error("identity mismatch: expected {expected:?}, sent {actual:?}")]
    IdentityMismatch { expected: String, actual: String },
    #[error("step2 part A must have 4 fields, got {0}")]
    Step2Fields(usize),
    #[error("ticket must have 2 fields, got {0}")]
    TicketFields(usize),
    #[error("STEP5 verification failed: f(N2) mismatch")]
    VerificationFailed,
    #[error("unknown identity: {0:?}")]
    UnknownIdentity(String),
    #[error("initiator and responder must differ, both are {0:?}")]
    SameIdentity(String),
    #[error("expected {expected}, got {actual}")]
    UnexpectedStep {
        expected: &'static str,
        actual: &'static str,
    },
    #[error("invalid JSON message: {0}")]
    Json(#[from] serde_json::Error),
    #[error(transparent)]
    Codec(#[from] CodecError),
    #[error(transparent)]
    Mode(#[from] ModeError),
}

fn validate_field(value: &str, field: &'static str) -> Result<(), MessageError> {
    if value.is_empty() {
        return Err(MessageError::Empty { field });
    }
    if !value.is_ascii() {
        return Err(MessageError::NotAscii {
            field,
            value: value.to_string(),
        });
    }
    if value.chars().any(char::is_control) {
        return Err(MessageError::ControlChar {
            field,
            value: value.to_string(),
        });
    }
    if value.contains('|') {
        return Err(MessageError::Delimiter {
            field,
            value: value.to_string(),
        });
    }
    Ok(())
}

/// A validated identity such as `alice` or `bob`.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Id(String);

impl Id {
    pub fn new(value: &str) -> Result<Self, MessageError> {
        validate_field(value, "identity")?;
        Ok(Self(value.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for Id {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl Serialize for Id {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        serializer.serialize_str(&self.0)
    }
}

impl<'de> Deserialize<'de> for Id {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        let value = String::deserialize(deserializer)?;
        Id::new(&value).map_err(serde::de::Error::custom)
    }
}

/// A decimal nonce. Nonces generated by this program have eight digits.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Nonce(String);

impl Nonce {
    pub fn new(value: &str) -> Result<Self, MessageError> {
        if value.is_empty() || !value.bytes().all(|byte| byte.is_ascii_digit()) {
            return Err(MessageError::NonceFormat {
                value: value.to_string(),
            });
        }
        Ok(Self(value.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for Nonce {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl Serialize for Nonce {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        serializer.serialize_str(&self.0)
    }
}

impl<'de> Deserialize<'de> for Nonce {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        let value = String::deserialize(deserializer)?;
        Nonce::new(&value).map_err(serde::de::Error::custom)
    }
}

/// Every message exchanged between the KDC and the peers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Message {
    Step1 {
        initiator: Id,
        responder: Id,
        nonce: Nonce,
    },
    Step2 {
        for_initiator: Hex,
        ticket: Hex,
    },
    Step3 {
        ticket: Hex,
    },
    Step4 {
        ciphertext: Hex,
    },
    Step5 {
        ciphertext: Hex,
    },
    Msg {
        ciphertext: Hex,
    },
    Bye,
    Error {
        message: String,
    },
}

impl Message {
    pub fn kind(&self) -> &'static str {
        match self {
            Self::Step1 { .. } => "STEP1",
            Self::Step2 { .. } => "STEP2",
            Self::Step3 { .. } => "STEP3",
            Self::Step4 { .. } => "STEP4",
            Self::Step5 { .. } => "STEP5",
            Self::Msg { .. } => "MSG",
            Self::Bye => "BYE",
            Self::Error { .. } => "ERROR",
        }
    }

    pub fn to_line(&self) -> String {
        serde_json::to_string(self).expect("message serialization cannot fail")
    }

    pub fn parse(line: &str) -> Result<Self, MessageError> {
        Ok(serde_json::from_str(line.trim())?)
    }
}
